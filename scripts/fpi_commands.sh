#!/usr/bin/env bash

set -euo pipefail

project_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
env_file="${1:-$HOME/.config/env_vars/dev-ai.env}"
env_file="${env_file/#\~/$HOME}"

if [[ ! -f "$project_dir/docker-compose.yml" ]]; then
  printf 'Could not find docker-compose.yml in %s\n' "$project_dir" >&2
  exit 1
fi

if [[ ! -r "$env_file" ]]; then
  printf 'Environment file is missing or unreadable: %s\n' "$env_file" >&2
  printf 'Usage: %s /absolute/path/to/dev-ai.env\n' "$0" >&2
  exit 1
fi

config_dir="$HOME/.config/gen-ai-wrapper-market-data-analysis"
helper_file="$config_dir/fpi-compose.sh"
bashrc_file="$HOME/.bashrc"
mkdir -p "$config_dir"

printf -v quoted_project '%q' "$project_dir"
printf -v quoted_env '%q' "$env_file"

cat > "$helper_file" <<EOF
# Generated by scripts/install_fpi_commands.sh; rerun it to update these paths.
_fpi_project_dir=$quoted_project
_fpi_env_file=$quoted_env

_fpi_compose() {
  docker compose --project-directory "\$_fpi_project_dir" \\
    --env-file "\$_fpi_env_file" \\
    -f "\$_fpi_project_dir/docker-compose.yml" "\$@"
}

fpi_up() { _fpi_compose up -d "\$@"; }
fpi_down() { _fpi_compose down "\$@"; }
fpi_restart() { _fpi_compose up -d --force-recreate "\$@"; }
fpi_build() { _fpi_compose build "\$@"; }
EOF

touch "$bashrc_file"

# Remove the earlier inline fpi_* functions if they were pasted into ~/.bashrc.
python3 - "$bashrc_file" <<'PY'
from pathlib import Path
import sys

path = Path(sys.argv[1])
text = path.read_text(encoding="utf-8")
start = text.find(
    "# FastAPI AI service on port 8002. These do not replace dev_up, dev_down, or dev_restart."
)
if start != -1:
    end = text.find("\n# ", start + 1)
    if end == -1:
        end = len(text)
    path.write_text(text[:start].rstrip() + "\n", encoding="utf-8")
PY

source_line='source "$HOME/.config/gen-ai-wrapper-market-data-analysis/fpi-compose.sh"'
if ! grep -Fqx "$source_line" "$bashrc_file"; then
  printf '\n# FastAPI AI service Docker Compose shortcuts\n%s\n' "$source_line" >> "$bashrc_file"
fi

printf 'Installed fpi_up, fpi_down, and fpi_restart in %s\n' "$helper_file"
printf 'Run: source %s\n' "$bashrc_file"
